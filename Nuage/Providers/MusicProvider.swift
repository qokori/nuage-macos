//
//  MusicProvider.swift
//  Nuage
//
//  Multi-source seam. Every music service (SoundCloud and Yandex Music now,
//  Spotify later) sits behind `MusicProvider`. Shared UI and the player
//  talk to services through the neutral `Media*` models below, never through
//  a service's own API types.
//

import Foundation
import AVFoundation
import Combine

struct NoStreamError: Error {}

enum ProviderID: String, CaseIterable, Codable, Hashable, Identifiable {
    case soundCloud = "soundcloud"
    case spotify = "spotify"
    case yandexMusic = "yandex-music"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .soundCloud: return "SoundCloud"
        case .spotify: return "Spotify"
        case .yandexMusic: return "Яндекс Музыка"
        }
    }

    /// SF Symbol shown next to the service's name and on its rows.
    var iconName: String {
        switch self {
        case .soundCloud: return "cloud.fill"
        case .spotify: return "dot.radiowaves.right"
        case .yandexMusic: return "music.note"
        }
    }

    /// The name of the service's personal radio (`ProviderCapabilities.radio`).
    var radioTitle: String {
        switch self {
        case .yandexMusic: return "Моя волна"
        case .soundCloud, .spotify: return "Radio"
        }
    }

}

/// What a provider can do. The UI hides what a provider lacks instead of failing on tap.
struct ProviderCapabilities: OptionSet, Hashable {

    let rawValue: Int

    static let search = ProviderCapabilities(rawValue: 1 << 0)
    static let likes = ProviderCapabilities(rawValue: 1 << 1)
    static let toggleLike = ProviderCapabilities(rawValue: 1 << 2)
    static let playlists = ProviderCapabilities(rawValue: 1 << 3)
    static let editPlaylists = ProviderCapabilities(rawValue: 1 << 4)
    static let feed = ProviderCapabilities(rawValue: 1 << 5)
    static let history = ProviderCapabilities(rawValue: 1 << 6)
    static let waveform = ProviderCapabilities(rawValue: 1 << 7)
    static let comments = ProviderCapabilities(rawValue: 1 << 8)
    static let reposts = ProviderCapabilities(rawValue: 1 << 9)
    /// Curated selections (SoundCloud Discover).
    static let discover = ProviderCapabilities(rawValue: 1 << 10)
    /// Radio stations generated from a track or an artist.
    static let stations = ProviderCapabilities(rawValue: 1 << 11)
    /// Followed artists and artist pages.
    static let following = ProviderCapabilities(rawValue: 1 << 12)
    /// A personal endless radio (Yandex Music's «Моя волна»), see `RadioSession`.
    static let radio = ProviderCapabilities(rawValue: 1 << 13)

}

// MARK: - Neutral models

/// The same raw id can exist in two services, so every id carries its provider.
struct MediaID: Hashable, Codable {

    var provider: ProviderID
    var rawID: String

}

extension MediaID: CustomStringConvertible {

    var description: String { "\(provider.rawValue):\(rawID)" }

}

struct MediaArtist: Identifiable, Hashable, Codable {

    var id: MediaID
    var name: String
    var avatarURL: URL?
    var permalinkURL: URL?
    var followerCount: Int? = nil
    var trackCount: Int? = nil

    var provider: ProviderID { id.provider }

}

/// Counters a service exposes for a track. Any of them can be missing.
struct MediaStats: Hashable, Codable {

    var plays: Int?
    var likes: Int?
    var reposts: Int?

}

struct MediaTrack: Identifiable, Hashable, Codable {

    var id: MediaID
    var title: String
    var artist: MediaArtist
    var artworkURL: URL?
    var duration: TimeInterval
    var permalinkURL: URL?
    var waveformURL: URL?
    /// Provider-specific hint to start playback without another lookup
    /// (SoundCloud: the transcoding URL). `nil` means the provider resolves the track by id.
    var streamLocator: URL?
    var description: String? = nil
    var stats: MediaStats? = nil

    var provider: ProviderID { id.provider }

}

struct MediaPlaylist: Identifiable, Hashable, Codable {

    var id: MediaID
    var title: String
    var owner: MediaArtist?
    var artworkURL: URL?
    var trackCount: Int?
    /// Created by the signed-in user (as opposed to liked or followed).
    var isOwned: Bool
    /// Generated by the service: stations, mixes, "playlist of the day".
    var isSystem: Bool
    var description: String? = nil
    var permalinkURL: URL? = nil
    /// The first tracks, when the service sends them along with the playlist.
    var previewTracks: [MediaTrack]? = nil

    var provider: ProviderID { id.provider }

}

struct SearchResults {

    var tracks = [MediaTrack]()
    var artists = [MediaArtist]()
    var playlists = [MediaPlaylist]()

    var isEmpty: Bool { tracks.isEmpty && artists.isEmpty && playlists.isEmpty }

}

// MARK: - Playback

/// How a track reaches the speakers.
enum PlaybackSource {
    /// Nuage plays the audio itself through `AVPlayer` (SoundCloud, Yandex Music).
    case asset(AVURLAsset)
    /// Another engine plays the audio (the Spotify app or a Web Playback SDK page);
    /// Nuage only sends commands and mirrors progress.
    case remote(any RemotePlaybackController)
}

protocol RemotePlaybackController: AnyObject {

    var progressPublisher: AnyPublisher<TimeInterval, Never> { get }
    var isPlayingPublisher: AnyPublisher<Bool, Never> { get }
    var didFinishPublisher: AnyPublisher<Void, Never> { get }

    func play(_ track: MediaTrack)
    func pause()
    func resume()
    func seek(to seconds: TimeInterval)
    func setVolume(_ volume: Float)

}

// MARK: - Radio

/// An endless queue the service fills for the listener (Yandex Music's «Моя волна»).
/// The player asks for the next batch before the queue runs out and reports what the
/// listener does with each track, so the service can tune what comes next.
/// Used on the main thread.
protocol RadioSession: AnyObject {

    var provider: ProviderID { get }
    var title: String { get }
    /// `false` once the account the radio belongs to signed out or was replaced:
    /// it then loads and reports nothing.
    var isActive: Bool { get }

    /// More tracks. `last` is the last radio track queued so far; `nil` asks for the first batch.
    func nextBatch(after last: MediaTrack?) -> AnyPublisher<[MediaTrack], Error>
    func didStart(_ track: MediaTrack)
    /// The track played to its end.
    func didFinish(_ track: MediaTrack, playedSeconds: TimeInterval)
    /// The listener moved on before the end.
    func didSkip(_ track: MediaTrack, playedSeconds: TimeInterval)
    /// The listener does not want the track. Counts as a skip too; the player moves on.
    func dislike(_ track: MediaTrack, playedSeconds: TimeInterval)

}

/// The radio's account signed out, or another account signed in.
struct RadioEndedError: LocalizedError {

    var errorDescription: String? {
        return "the account it belongs to is no longer signed in."
    }

}

// MARK: - Provider

enum AuthState: Equatable {
    case signedOut
    case signedIn(displayName: String?)
    case expired

    var isSignedIn: Bool {
        if case .signedIn = self { return true }
        return false
    }
}

struct ProviderUnsupportedError: Error {

    var provider: ProviderID
    var capability: String

}

/// One music service. Sign-in UI differs per service (web login, OAuth, pasted token),
/// so it stays on the concrete provider; the protocol only exposes the resulting state.
protocol MusicProvider: AnyObject {

    var id: ProviderID { get }
    var capabilities: ProviderCapabilities { get }

    // MARK: Auth

    var authState: AuthState { get }
    var authStatePublisher: AnyPublisher<AuthState, Never> { get }
    /// Restores a saved session at launch. Returns `true` when the provider is signed in.
    @discardableResult func restoreSession() -> Bool
    func signOut()
    /// A problem with the account to show in Accounts and the player
    /// (a rejected token, no subscription). `nil` when all is well.
    var accountNotice: String? { get }

    // MARK: Catalog and library

    func search(_ query: String, limit: Int) -> AnyPublisher<SearchResults, Error>
    /// Every liked track, newest first.
    func likedTracks() -> AnyPublisher<[MediaTrack], Error>
    func setLiked(_ liked: Bool, track: MediaTrack) -> AnyPublisher<Void, Error>
    /// The user's library: created, liked and followed playlists.
    func playlists() -> AnyPublisher<[MediaPlaylist], Error>
    func setLiked(_ liked: Bool, playlist: MediaPlaylist) -> AnyPublisher<Void, Error>
    func tracks(in playlist: MediaPlaylist) -> AnyPublisher<[MediaTrack], Error>
    func add(_ track: MediaTrack, to playlist: MediaPlaylist) -> AnyPublisher<Void, Error>

    // MARK: Playback

    func playbackSource(for track: MediaTrack) -> AnyPublisher<PlaybackSource, Error>
    /// Called when a track of this provider starts playing (history, scrobbling).
    func didStartPlayback(of track: MediaTrack)
    /// A new session of the personal radio. `nil` without `.radio` or while signed out.
    func radio() -> (any RadioSession)?

}

extension MusicProvider {

    var displayName: String { id.displayName }

    var isSignedIn: Bool { authState.isSignedIn }

    var accountNotice: String? { nil }

    func didStartPlayback(of track: MediaTrack) {}

    func radio() -> (any RadioSession)? { nil }

    func unsupported<T>(_ capability: String) -> AnyPublisher<T, Error> {
        return Fail(error: ProviderUnsupportedError(provider: id, capability: capability))
            .eraseToAnyPublisher()
    }

}
