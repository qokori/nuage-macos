//
//  MusicProvider.swift
//  Nuage
//
//  Multi-source seam. Every music service (SoundCloud now, Spotify and
//  Yandex Music later) sits behind `MusicProvider`. Shared UI and the player
//  talk to services through the neutral `Media*` models below, never through
//  a service's own API types.
//

import Foundation
import AVFoundation
import Combine

struct NoStreamError: Error {}

enum ProviderID: String, CaseIterable, Codable, Hashable, Identifiable {
    case soundCloud = "soundcloud"
    case spotify = "spotify"
    case yandexMusic = "yandex-music"

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .soundCloud: return "SoundCloud"
        case .spotify: return "Spotify"
        case .yandexMusic: return "Яндекс Музыка"
        }
    }

}

/// What a provider can do. The UI hides what a provider lacks instead of failing on tap.
struct ProviderCapabilities: OptionSet, Hashable {

    let rawValue: Int

    static let search = ProviderCapabilities(rawValue: 1 << 0)
    static let likes = ProviderCapabilities(rawValue: 1 << 1)
    static let toggleLike = ProviderCapabilities(rawValue: 1 << 2)
    static let playlists = ProviderCapabilities(rawValue: 1 << 3)
    static let editPlaylists = ProviderCapabilities(rawValue: 1 << 4)
    static let feed = ProviderCapabilities(rawValue: 1 << 5)
    static let history = ProviderCapabilities(rawValue: 1 << 6)
    static let waveform = ProviderCapabilities(rawValue: 1 << 7)
    static let comments = ProviderCapabilities(rawValue: 1 << 8)
    static let reposts = ProviderCapabilities(rawValue: 1 << 9)

}

// MARK: - Neutral models

/// The same raw id can exist in two services, so every id carries its provider.
struct MediaID: Hashable, Codable {

    var provider: ProviderID
    var rawID: String

}

struct MediaArtist: Identifiable, Hashable, Codable {

    var id: MediaID
    var name: String
    var avatarURL: URL?
    var permalinkURL: URL?

}

struct MediaTrack: Identifiable, Hashable, Codable {

    var id: MediaID
    var title: String
    var artist: MediaArtist
    var artworkURL: URL?
    var duration: TimeInterval
    var permalinkURL: URL?
    var waveformURL: URL?
    /// Provider-specific hint to start playback without another lookup
    /// (SoundCloud: the transcoding URL). `nil` means the provider resolves the track by id.
    var streamLocator: URL?

    var provider: ProviderID { id.provider }

}

struct MediaPlaylist: Identifiable, Hashable, Codable {

    var id: MediaID
    var title: String
    var owner: MediaArtist?
    var artworkURL: URL?
    var trackCount: Int?
    /// Created by the signed-in user (as opposed to liked or followed).
    var isOwned: Bool
    /// Generated by the service: stations, mixes, "playlist of the day".
    var isSystem: Bool

}

struct SearchResults {

    var tracks = [MediaTrack]()
    var artists = [MediaArtist]()
    var playlists = [MediaPlaylist]()

    var isEmpty: Bool { tracks.isEmpty && artists.isEmpty && playlists.isEmpty }

}

// MARK: - Playback

/// How a track reaches the speakers.
enum PlaybackSource {
    /// Nuage plays the audio itself through `AVPlayer` (SoundCloud, Yandex Music).
    case asset(AVURLAsset)
    /// Another engine plays the audio (the Spotify app or a Web Playback SDK page);
    /// Nuage only sends commands and mirrors progress.
    case remote(any RemotePlaybackController)
}

protocol RemotePlaybackController: AnyObject {

    var progressPublisher: AnyPublisher<TimeInterval, Never> { get }
    var didFinishPublisher: AnyPublisher<Void, Never> { get }

    func play(_ track: MediaTrack)
    func pause()
    func resume()
    func seek(to seconds: TimeInterval)
    func setVolume(_ volume: Float)

}

// MARK: - Provider

enum AuthState: Equatable {
    case signedOut
    case signedIn(displayName: String?)
    case expired
}

struct ProviderUnsupportedError: Error {

    var provider: ProviderID
    var capability: String

}

/// One music service. Sign-in UI differs per service (web login, OAuth, pasted token),
/// so it stays on the concrete provider; the protocol only exposes the resulting state.
protocol MusicProvider: AnyObject {

    var id: ProviderID { get }
    var capabilities: ProviderCapabilities { get }

    // MARK: Auth

    var authState: AuthState { get }
    var authStatePublisher: AnyPublisher<AuthState, Never> { get }
    /// Restores a saved session at launch. Returns `true` when the provider is signed in.
    @discardableResult func restoreSession() -> Bool
    func signOut()

    // MARK: Catalog and library

    func search(_ query: String, limit: Int) -> AnyPublisher<SearchResults, Error>
    func likedTracks(limit: Int) -> AnyPublisher<[MediaTrack], Error>
    func setLiked(_ liked: Bool, track: MediaTrack) -> AnyPublisher<Void, Error>
    func playlists() -> AnyPublisher<[MediaPlaylist], Error>
    func tracks(in playlist: MediaPlaylist) -> AnyPublisher<[MediaTrack], Error>

    // MARK: Playback

    func playbackSource(for track: MediaTrack) -> AnyPublisher<PlaybackSource, Error>
    /// Called when a track of this provider starts playing (history, scrobbling).
    func didStartPlayback(of track: MediaTrack)

}

extension MusicProvider {

    var displayName: String { id.displayName }

    var isSignedIn: Bool {
        if case .signedIn = authState { return true }
        return false
    }

    func didStartPlayback(of track: MediaTrack) {}

    func unsupported<T>(_ capability: String) -> AnyPublisher<T, Error> {
        return Fail(error: ProviderUnsupportedError(provider: id, capability: capability))
            .eraseToAnyPublisher()
    }

}
